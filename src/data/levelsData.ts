export function getLoveTier(lp: number) {
  for (let i = LOVE_LEVEL_TIERS.length - 1; i >= 0; i--) {
    if (lp >= LOVE_LEVEL_TIERS[i].minLp) {
      return LOVE_LEVEL_TIERS[i];
    }
  }
  return LOVE_LEVEL_TIERS[0];
}

export function getNextLoveTier(lp: number) {
  for (const tier of LOVE_LEVEL_TIERS) {
    if (lp < tier.minLp) {
      return tier;
    }
  }
  return null;
}
